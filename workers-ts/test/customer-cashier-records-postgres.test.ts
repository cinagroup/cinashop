import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { eq, sql } from 'drizzle-orm';
import { Hono } from 'hono';
import type { AppVariables, Env } from '../src/env';
import { createContainerFromDb, type DbClient } from '../src/lib/di';
import { authMiddleware } from '../src/middleware/auth';
import { errorHandler } from '../src/middleware/error';
import { createToken, md5, type TokenType } from '../src/utils/jwt';
import { storeOrder, storeOrderCartInfo, storeOrderOutbox, storeOrderStatus, storeProduct, storeProductAttrValue, storeService, user } from '../src/models/schema';
import { CustomerWorkCashierReadService } from '../src/services/customer-work/CustomerWorkCashierReadService';
import { cashierRecord, cashierRecords } from '../src/controllers/api/v1/CustomerWorkCashierController';
import { authorizeCustomerWorkActor } from '../src/services/customer-work/CustomerWorkScope';
import { createCustomerCashierSecondCardWithRuntime } from '../src/services/customer-work/CustomerWorkCashierService';
import { customerCashierSecondCardFixture } from './helpers/customerCashierSecondCardFixture';
import { observeIntegralReadDb } from './helpers/integralProductReadFixture';

/** Complete native PG16 contract. Positive records are generated by actual
 * cashier creation/payment; forged rows occur only in explicit refusal tests. */
describe('ordinary customer own cashier second-card record PG16 contract', () => {
  let f: Awaited<ReturnType<typeof customerCashierSecondCardFixture>>;
  beforeAll(async () => { f = await customerCashierSecondCardFixture(); }, 180000);
  beforeEach(async () => { await f.reset(); });
  afterAll(async () => { await f?.close(); }, 30000);

  const reader = (db: DbClient = f.db) => new CustomerWorkCashierReadService(createContainerFromDb(db), f.env);
  const scope = async () => (await authorizeCustomerWorkActor(f.db, f.actor())).scope_key;
  const http = (db: DbClient = f.db) => {
    const h = new Hono<{ Bindings: Env; Variables: AppVariables }>();
    h.use('*', async (c, next) => { c.set('container', createContainerFromDb(db)); await next(); });
    h.use('*', authMiddleware({ force: true }));
    h.onError(errorHandler);
    h.get('/records', cashierRecords);
    h.get('/records/:id', cashierRecord);
    return h;
  };
  const token = async (uid = 101, type: TokenType = 'api', auth = md5('owned-financial-password')) =>
    (await createToken(uid, type, auth, f.env.APP_KEY)).token;
  const request = async (path: string, bearer: string | undefined = undefined, db: DbClient = f.db) =>
    http(db).request(path, { headers: bearer ? { Authorization: `Bearer ${bearer}` } : {} }, f.env);
  const snapshot = async () => {
    const rows = await f.maintenanceDb.execute<{ data: unknown }>(sql`SELECT jsonb_build_object(
      'orders',(SELECT COALESCE(jsonb_agg(to_jsonb(o) ORDER BY o.id),'[]'::jsonb) FROM public.store_order o),
      'carts',(SELECT COALESCE(jsonb_agg(to_jsonb(c) ORDER BY c.id),'[]'::jsonb) FROM public.store_order_cart_info c),
      'origins',(SELECT COALESCE(jsonb_agg(to_jsonb(o) ORDER BY o.order_id),'[]'::jsonb) FROM public.cashier_second_card_origin_v1 o),
      'payments',(SELECT COALESCE(jsonb_agg(to_jsonb(p) ORDER BY p.order_id),'[]'::jsonb) FROM public.cashier_second_card_payment_v1 p),
      'audits',(SELECT COALESCE(jsonb_agg(to_jsonb(s) ORDER BY s.id),'[]'::jsonb) FROM public.store_order_status s),
      'events',(SELECT COALESCE(jsonb_agg(to_jsonb(e) ORDER BY e.id),'[]'::jsonb) FROM public.store_order_outbox e)
      ) AS data`);
    return rows[0].data;
  };

  it('reads the genuine unpaid creation and original immutable SKU snapshot without dispatching a business effect', async () => {
    const created = await f.create(await f.input({ mark: 'PRIVATE-CASHIER-MARK' })), before = await snapshot();
    const result = await reader().records(f.actor(), { scope_key: await scope() });
    expect(result).toMatchObject({ version: 'customer-work-cashier-read-v1', actor_uid: 101,
      principal: { kind: 'customer-order-manager', service_id: 1, scope: 'global' },
      data: { scope: 'own-second-card-creations', limit: 20, has_more: false, next_cursor: null } });
    expect(result.data.list).toHaveLength(1);
    expect(result.data.list[0]).toMatchObject({ id: created.order.id, order_no: created.order.orderId,
      creator_uid: 101, buyer_uid: 11, quantity: 2, amount: created.order.payPrice, paid: 0, root_retired: false });
    const detail = await reader().record(f.actor(), String(created.order.id), { order_no: created.order.orderId });
    expect(detail.data.creation).toMatchObject({ request_key: created.input.request_key, service_id: 1 });
    expect(detail.data.creation.created_at).toMatch(/^\d{4}-\d{2}-\d{2}T/);
    expect(detail.data.items).toMatchObject([{ product_id: 70, sku_unique: 'qared001', quantity: 2, write_times: 6 }]);
    expect(detail.data.payment).toBe(null);
    expect(JSON.stringify(detail)).not.toMatch(/PRIVATE-CASHIER-MARK|owned-financial-password|custom_form|tourist_hash|cart_info|disk_info/);
    expect(await snapshot()).toEqual(before);
    const [liveProduct] = await f.maintenanceDb.select({ storeName: storeProduct.storeName }).from(storeProduct).where(eq(storeProduct.id, 70));
    const [liveSku] = await f.maintenanceDb.select({ suk: storeProductAttrValue.suk, price: storeProductAttrValue.price }).from(storeProductAttrValue).where(eq(storeProductAttrValue.id, 1));
    try {
      await f.maintenanceDb.update(storeProduct).set({ storeName: 'MUTABLE-CATALOG-NAME' }).where(eq(storeProduct.id, 70));
      await f.maintenanceDb.update(storeProductAttrValue).set({ suk: 'MUTABLE-CATALOG-SKU', price: '999.00' }).where(eq(storeProductAttrValue.id, 1));
      expect((await reader().record(f.actor(), created.order.id, { order_no: created.order.orderId })).data.items).toEqual(detail.data.items);
    } finally {
      await f.maintenanceDb.update(storeProduct).set(liveProduct).where(eq(storeProduct.id, 70));
      await f.maintenanceDb.update(storeProductAttrValue).set(liveSku).where(eq(storeProductAttrValue.id, 1));
    }
  });

  it('reads genuine UID0 and zero cash payment proofs while keeping the operator UID separate', async () => {
    await f.reset('0.00');
    const { order } = await f.create(await f.input({ buyer_uid: 0, tourist_key: 'private-guest-record-001' }));
    const paid = await f.cash(order); await f.processPaid(paid.outbox!);
    const before = await snapshot(), detail = await reader().record(f.actor(), order.id, { order_no: order.orderId });
    expect(detail.data.record).toMatchObject({ creator_uid: 101, buyer_uid: 0, paid: 1, amount: '0.00', pay_type: 'cash' });
    expect(detail.data.payment).toMatchObject({ amount: '0.00', payment_kind: 'zero', outbox_id: paid.outbox!.id });
    expect(detail.data.payment!.origin_hash).toBe(detail.data.creation.origin_hash);
    expect(JSON.stringify(detail)).not.toContain('private-guest-record-001');
    expect(await snapshot()).toEqual(before);
  });

  it('verifies a genuine nonzero cash payment and rejects an event rebound to another aggregate', async () => {
    const { order } = await f.create(), paid = await f.cash(order);
    await f.processPaid(paid.outbox!);
    const result = await reader().record(f.actor(), order.id, { order_no: order.orderId });
    expect(Number(order.payPrice)).toBeGreaterThan(0);
    expect(result.data.payment).toMatchObject({ amount: order.payPrice, payment_kind: 'cash', outbox_id: paid.outbox!.id });
    await f.maintenanceDb.update(storeOrderOutbox).set({ aggregateId: order.id + 1 }).where(eq(storeOrderOutbox.id, paid.outbox!.id));
    const before = await snapshot();
    await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
    expect(await snapshot()).toEqual(before);
  });

  it('does not authorize matching staff flags or another current customer operator without an owned immutable origin', async () => {
    const own = await f.create();
    await f.maintenanceDb.update(storeService).set({ customer: 1 }).where(eq(storeService.uid, 102));
    const otherScope = await authorizeCustomerWorkActor(f.db, f.actor(102));
    const foreignInput = await f.input({ scope_key: otherScope.scope_key, quantity: 1 });
    const foreign = await createCustomerCashierSecondCardWithRuntime(f.container, f.runtime, f.actor(102), foreignInput);
    await f.maintenanceDb.insert(storeOrder).values({ id: 900, orderId: 'forged-staff-second-card', unique: 'forged-staff-second-card',
      uid: 11, staffId: 101, isChannel: 2, productType: 4, shippingType: 2, storeId: 0, paid: 0 });
    expect((await reader().records(f.actor(), {})).data.list.map(row => row.order_no)).toEqual([own.order.orderId]);
    expect((await reader().records(f.actor(102), {})).data.list.map(row => row.order_no)).toEqual([foreign.orderId]);
    await expect(reader().record(f.actor(102), own.order.id, { order_no: own.order.orderId })).rejects.toThrow();
    await expect(reader().record(f.actor(), 900, { order_no: 'forged-staff-second-card' })).rejects.toThrow();
  });

  it('binds the actual root identity and refuses changed buyer operator channel product or delivery facts', async () => {
    const { order } = await f.create();
    for (const patch of [{ uid: 12 }, { staffId: 102 }, { isChannel: 0 }, { productType: 0 }, { shippingType: 1 }, { storeId: 7 }]) {
      await f.maintenanceDb.update(storeOrder).set(patch).where(eq(storeOrder.id, order.id));
      await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
      await f.maintenanceDb.update(storeOrder).set({ uid: order.uid, staffId: order.staffId, isChannel: order.isChannel,
        productType: order.productType, shippingType: order.shippingType, storeId: order.storeId }).where(eq(storeOrder.id, order.id));
    }
    await f.maintenanceDb.update(storeOrder).set({ orderId: 'changed-root-number' }).where(eq(storeOrder.id, order.id));
    await expect(reader().record(f.actor(), order.id, { order_no: 'changed-root-number' })).rejects.toThrow();
  });

  it('refuses a changed immutable cart JSON and a missing actual creation audit', async () => {
    const { order } = await f.create(), actual = await f.actual(order.id), cart = actual.carts[0];
    for (const patch of [{ cartInfo: '{}' }, { cartInfo: ' '.repeat(262145) }, { cartNum: cart.cartNum + 1 }, { writeTimes: cart.writeTimes + 1 }]) {
      await f.maintenanceDb.update(storeOrderCartInfo).set(patch).where(eq(storeOrderCartInfo.id, cart.id));
      await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
      await f.maintenanceDb.update(storeOrderCartInfo).set({ cartInfo: cart.cartInfo, cartNum: cart.cartNum, writeTimes: cart.writeTimes }).where(eq(storeOrderCartInfo.id, cart.id));
    }
    await f.maintenanceDb.insert(storeOrderCartInfo).values({ ...cart, id: cart.id + 1000, cartId: 'unproven-extra-row', unique: 'unproven-extra-row' });
    await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
    await f.maintenanceDb.delete(storeOrderCartInfo).where(eq(storeOrderCartInfo.cartId, 'unproven-extra-row'));
    await f.maintenanceDb.delete(storeOrderStatus).where(eq(storeOrderStatus.changeType, 'customer_cashier_create'));
    await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
  });

  it('does not treat a forged paid bit as an original cash payment receipt', async () => {
    const { order } = await f.create();
    await f.maintenanceDb.update(storeOrder).set({ paid: 1, payType: 'cash', payTime: Math.floor(Date.now() / 1000) }).where(eq(storeOrder.id, order.id));
    const before = await snapshot();
    await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
    expect(await snapshot()).toEqual(before);
  });

  it('retains buyer-deleted original creation history but excludes system deletion and never aliases a physical ID to a business number', async () => {
    const { order } = await f.create();
    await f.maintenanceDb.update(storeOrder).set({ isDel: 1, pid: -1 }).where(eq(storeOrder.id, order.id));
    expect((await reader().records(f.actor(), {})).data.list[0]).toMatchObject({ id: order.id, root_retired: true });
    expect((await reader().record(f.actor(), order.id, { order_no: order.orderId })).data.record.root_retired).toBe(true);
    await expect(reader().record(f.actor(), order.id, { order_no: String(order.id) })).rejects.toThrow();
    await f.maintenanceDb.update(storeOrder).set({ isSystemDel: 1 }).where(eq(storeOrder.id, order.id));
    expect((await reader().records(f.actor(), {})).data.list).toEqual([]);
    await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
  });

  it('paginates complete creation sort keys without duplicate roots and excludes later insertions from an existing cursor', async () => {
    const first = await f.create(await f.input({ quantity: 1 })), second = await f.create(await f.input({ quantity: 1 }));
    const page1 = await reader().records(f.actor(), { limit: '1' });
    expect(page1.data).toMatchObject({ has_more: true, limit: 1 });
    expect(page1.data.list.map(row => row.id)).toEqual([second.order.id]);
    expect(page1.data.next_cursor).toEqual(expect.any(String));
    await f.create(await f.input({ quantity: 1 }));
    const page2 = await reader().records(f.actor(), { limit: '1', cursor: page1.data.next_cursor! });
    expect(page2.data.list.map(row => row.id)).toEqual([first.order.id]);
    expect(page2.data).toMatchObject({ has_more: false, next_cursor: null });
  });

  it('binds opaque cursor positions to actor current scope and exact order-number search', async () => {
    await f.create(await f.input({ quantity: 1 })); const second = await f.create(await f.input({ quantity: 1 }));
    const page = await reader().records(f.actor(), { limit: '1' }), cursor = page.data.next_cursor!;
    expect((await reader().records(f.actor(), { order_no: second.order.orderId })).data.list.map(row => row.id)).toEqual([second.order.id]);
    await expect(reader().records(f.actor(), { order_no: second.order.orderId, cursor })).rejects.toThrow();
    await f.maintenanceDb.update(storeService).set({ customer: 1 }).where(eq(storeService.uid, 102));
    await expect(reader().records(f.actor(102), { cursor })).rejects.toThrow();
    await f.maintenanceDb.update(storeService).set({ merId: 77 }).where(eq(storeService.uid, 101));
    await expect(reader().records(f.actor(), { cursor })).rejects.toThrow();
    expect((await reader().records(f.actor(), {})).data.list).toHaveLength(2);
  });

  it('rejects unsupported identity selectors legacy pagination malformed bounds cursors and noncanonical physical IDs', async () => {
    const r = reader();
    const invalidQueries: Array<Record<string,string>> = [{ actor_uid: '101' }, { buyer_uid: '11' }, { staff_id: '101' }, { tourist_uid: 'guest' },
      { page: '1' }, { keyword: '%' }, { status: '0' }, { limit: '0' }, { limit: '51' }, { limit: '01' },
      { limit: '1.0' }, { cursor: 'invalid' }, { cursor: 'x'.repeat(4097) }, { order_no: 'a%b' },
      { order_no: 'a_b%' }, { order_no: 'a\\b' }, { order_no: ' a' }, { scope_key: 'x' }];
    for (const query of invalidQueries) {
      await expect(r.records(f.actor(), query)).rejects.toThrow();
    }
    for (const id of ['01', '1e2', '1.0', '-1', '2147483648', 'owned-number']) {
      await expect(r.record(f.actor(), id, { order_no: 'owned-number' })).rejects.toThrow();
    }
    await expect(r.record(f.actor(), 101, {})).rejects.toThrow();
  });

  it('revalidates current customer status password scope and token lifetime rather than reusing a historical creation grant', async () => {
    const { order } = await f.create();
    for (const patch of [{ customer: 0 }, { accountStatus: 0 }, { isDel: 1 }]) {
      await f.maintenanceDb.update(storeService).set(patch).where(eq(storeService.uid, 101));
      await expect(reader().records(f.actor(), {})).rejects.toThrow();
      await f.maintenanceDb.update(storeService).set({ customer: 1, accountStatus: 1, isDel: 0 }).where(eq(storeService.uid, 101));
    }
    await expect(reader().record({ ...f.actor(), expires_at: Math.floor(Date.now() / 1000) - 1 }, order.id, { order_no: order.orderId })).rejects.toThrow();
    await f.maintenanceDb.update(user).set({ pwd: 'changed-record-password' }).where(eq(user.uid, 101));
    await expect(reader().records(f.actor(), {})).rejects.toThrow();
  });

  it('rejects a real role revocation after the read-only snapshot before returning protected records', async () => {
    await f.create(); let revoked = false;
    const db = observeIntegralReadDb(f.db, async (_tx, command) => {
      if (!revoked && /FROM\s+public\.cashier_second_card_origin_v1\b/i.test(command)) {
        revoked = true;
        await f.maintenanceDb.update(storeService).set({ customer: 0 }).where(eq(storeService.uid, 101));
      }
    });
    await expect(reader(db).records(f.actor(), {})).rejects.toThrow();
    expect(revoked).toBe(true);
  });

  it('uses a genuine non-owner read-only repeatable-read transaction with the existing stricter statement timeout restored after exit', async () => {
    await f.create(); const before = await snapshot(); let observed = false;
    await f.db.execute(sql`SET statement_timeout='250ms'`);
    try {
      const db = observeIntegralReadDb(f.db, async (tx, command) => {
        if (!observed && /FROM\s+public\.cashier_second_card_origin_v1\b/i.test(command)) {
          observed = true;
          const [settings] = await tx.execute<{ isolation: string; readonly: string; timeout: string; role: string; session: string; elevated: boolean }>(sql`
            SELECT current_setting('transaction_isolation') AS isolation,current_setting('transaction_read_only') AS readonly,
              current_setting('statement_timeout') AS timeout,current_user AS role,session_user AS session,
              (SELECT rolsuper OR rolcreatedb OR rolcreaterole OR rolinherit OR rolreplication OR rolbypassrls FROM pg_roles WHERE rolname=current_user) AS elevated`);
          expect(settings).toEqual({ isolation: 'repeatable read', readonly: 'on', timeout: '250ms', role: f.role, session: f.role, elevated: false });
          await expect(tx.transaction(async savepoint => { await savepoint.execute(sql`UPDATE public.store_order SET paid=paid WHERE id=-1`); })).rejects.toMatchObject({ cause: { code: '25006' } });
        }
      });
      expect((await reader(db).records(f.actor(), {})).data.list).toHaveLength(1);
      expect(observed).toBe(true);
      expect((await f.db.execute<{ timeout: string }>(sql`SELECT current_setting('statement_timeout') AS timeout`))[0].timeout).toBe('250ms');
      expect(await snapshot()).toEqual(before);
    } finally { await f.db.execute(sql`RESET statement_timeout`); }
  });

  it('runs real UserJWT HTTP authentication and rejects Admin Kefu and other staff identities before returning any data', async () => {
    const { order } = await f.create(), owned = await token();
    const response = await request(`/records?scope_key=${await scope()}`, owned);
    expect(response.headers.get('Cache-Control')).toBe('private, no-store');
    expect(await response.json()).toMatchObject({ status: 200, data: { actor_uid: 101, data: { list: [{ id: order.id }] } } });
    const detail = await request(`/records/${order.id}?order_no=${order.orderId}`, owned);
    expect(await detail.json()).toMatchObject({ status: 200, data: { data: { record: { id: order.id } } } });
    for (const bearer of [undefined, await token(101, 'admin'), await token(101, 'kefu'), await token(101, 'out'), await token(101, 'supplier'), await token(102), await token(103), await token(104), await token(105), await token(101, 'api', 'invalid-auth')]) {
      const denied = await request('/records', bearer), data = await denied.json() as { status: number; data: unknown };
      expect(data.status).not.toBe(200); expect(data.data).toBe(null);
    }
    for (const path of ['/records?limit=1&limit=2', `/records/${order.id}?order_no=${order.orderId}&order_no=${order.orderId}`, '/records?uid=101']) {
      const invalid = await request(path, owned), data = await invalid.json() as { status: number; data: unknown };
      expect(data.status).not.toBe(200); expect(data.data).toBe(null);
    }
  });

  it('fails closed on missing SELECT permission without granting or repairing the runtime catalog', async () => {
    const { order } = await f.create(), before = await snapshot();
    await f.exec(`REVOKE SELECT ON public.cashier_second_card_origin_v1 FROM "${f.role}"`);
    try {
      await expect(reader().record(f.actor(), order.id, { order_no: order.orderId })).rejects.toThrow();
      expect((await f.db.execute<{ allowed: boolean }>(sql`SELECT has_table_privilege(current_user,'public.cashier_second_card_origin_v1','SELECT') AS allowed`))[0].allowed).toBe(false);
      expect(await snapshot()).toEqual(before);
    } finally { await f.exec(`GRANT SELECT ON public.cashier_second_card_origin_v1 TO "${f.role}"`); }
  });
});
